"""The randomizer variant's tooling (R2a), on synthetic trees: no disc, no translation.

Covers scripts/mods/build_mod_variants.py's module layouts (--layout) and overlays, and scripts/rando/check_variant.py:
  * a mod with a grown REL (moved BSS), a REL of changed data shape and a module the base lacks gets its own tables,
    which reference the base's where nothing changed;
  * an extra chunk that covers a base chunk (the replaced chest actor) becomes an overlay of that chunk;
  * an extra chunk that only partly covers a base chunk is refused;
  * a mod without --layout still refuses nothing it used to accept, and writes its REL data as boot writes;
  * check_variant finds overlapping sections, data entries off their table, and chunks outside every section.
"""
import re
import struct
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts" / "mods"))
sys.path.insert(0, str(ROOT / "scripts" / "rando"))
import build_mod_variants as bmv  # noqa: E402
import check_variant as cv  # noqa: E402

BUILD = ROOT / "scripts" / "mods" / "build_mod_variants.py"


def dol(path, text=b"\x60\x00\x00\x00" * 4, addr=0x80003100):
    """A one-section DOL image."""
    header = bytearray(0x100)
    struct.pack_into(">I", header, 0x00, 0x100)
    struct.pack_into(">I", header, 0x48, addr)
    struct.pack_into(">I", header, 0x90, len(text))
    Path(path).write_bytes(bytes(header) + text)


def arr(name, data):
    body = ", ".join("0x%02Xu" % b for b in data)
    return "static const u8 %s[] = {%s};\n" % (name, body)


def write_tree(root, modules, data, chunks):
    """modules: {id: (file_size, [(index, linked, size)])}; data: {(id, section): bytes or None for BSS};
    chunks: {start: (end, source_text_suffix)} (REL chunks go to chunks_rel/)."""
    root = Path(root)
    (root / "chunks_rel").mkdir(parents=True)
    rm = "// Generated by generate_composite.py -- do not edit.\n"
    for mid, (fsize, secs) in sorted(modules.items()):
        rm += "static const StaticRecompRelSection s_rel_sec_%d[] = {\n" % mid
        rm += "".join("    {%du, %du, 0x%08Xu, 0x%08Xu},\n" % (mid, i, a, n) for i, a, n in secs)
        rm += "};\n"
    rm += "static const StaticRecompRelModule s_rel_modules[] = {\n"
    for mid, (fsize, secs) in sorted(modules.items()):
        rm += "    {%du, 0u, %du, 0x004Cu, %du, s_rel_sec_%d, %du},\n" % (mid, len(secs), fsize, mid, len(secs))
    rm += "};\n"
    (root / "rel_modules.inc").write_text(rm, newline="\n")
    di = "// Generated by generate_composite.py -- do not edit.\n"
    entries = []
    for (mid, si), payload in sorted(data.items()):
        secs = dict((i, (a, n)) for i, a, n in modules[mid][1])
        a, n = secs[si]
        if payload is not None:
            di += arr("s_rel_data_%d_%d" % (mid, si), payload)
        entries.append("    {%du, %du, 0x%08Xu, 0x%08Xu, %s},\n" % (
            mid, si, a, n, ("s_rel_data_%d_%d" % (mid, si)) if payload is not None else "NULL"))
    di += "static const BlueWakeRelData s_rel_data[] = {\n" + "".join(entries) + "};\n"
    di += "static const BlueWakeRelLifecycle s_rel_lifecycle[] = {\n"
    for mid, (fsize, secs) in sorted(modules.items()):
        di += "    {%du, 0x%08Xu},\n" % (mid, secs[1][1])
    di += "};\n"
    (root / "rel_data.inc").write_text(di, newline="\n")
    starts = sorted(chunks)
    gh = "static const u32 s_dolrecomp_chunk_starts[] = {\n" + "".join("    0x%08Xu,\n" % s for s in starts) + "};\n"
    gh += "static const u32 s_ends[] = {\n" + "".join("    0x%08Xu,\n" % chunks[s][0] for s in starts) + "};\n"
    (root / "generated_composite.h").write_text(gh, newline="\n")
    for s in starts:
        (root / "chunks_rel" / ("chunk_%08X.c" % s)).write_text(
            "#include \"../generated.h\"\nvoid func_%08X(CPUState* ctx) {\n    /* %s */\n}\n" % (s, chunks[s][1]),
            newline="\n")


# Module 5 grows (its BSS moves, a section 7 appears); module 6 has data of another size; module 7 is new; module 8's
# code is replaced by a chunk of another range (the chest actor).
BASE_MODULES = {
    5: (0x300, [(0, 0, 0), (1, 0xC0500100, 0x100), (4, 0xC0500200, 0x10), (6, 0xC0500304, 0x20), (7, 0, 0)]),
    6: (0x300, [(0, 0, 0), (1, 0xC0600100, 0x100), (4, 0xC0600200, 0x10)]),
    8: (0x400, [(0, 0, 0), (1, 0xC0800100, 0x100), (4, 0xC0800200, 0x10)]),
}
MOD_MODULES = {
    5: (0x340, [(0, 0, 0), (1, 0xC0500100, 0x100), (4, 0xC0500200, 0x10), (6, 0xC0500344, 0x20), (7, 0xC0500300, 0x40)]),
    6: (0x300, [(0, 0, 0), (1, 0xC0600100, 0x100), (4, 0xC0600200, 0x18)]),
    8: (0x440, [(0, 0, 0), (1, 0xC0800084, 0x140), (4, 0xC0800200, 0x10)]),
    9: (0x200, [(0, 0, 0), (1, 0xC0900084, 0x80), (4, 0xC0900104, 0x10)]),
}
BASE_DATA = {(5, 4): b"\x01" * 16, (5, 6): None, (6, 4): b"\x02" * 16, (8, 4): b"\x03" * 16}
MOD_DATA = {(5, 4): b"\x01" * 16, (5, 6): None, (6, 4): b"\x02" * 24, (9, 4): b"\x04" * 16, (8, 4): b"\x03" * 16}
BASE_CHUNKS = {0xC0500100: (0xC0500200, "base"), 0xC0600100: (0xC0600200, "base"),
               0xC08000F4: (0xC0800180, "base chest"), 0xC0800180: (0xC08001C0, "base chest 2")}
MOD_CHUNKS = {0xC0500100: (0xC0500200, "mod changed"), 0xC0500300: (0xC0500340, "section 7"),
              0xC0600100: (0xC0600200, "base"), 0xC0900084: (0xC0900104, "new module"),
              0xC0800084: (0xC08001C4, "replaced chest")}


class Variants(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.t = Path(self.tmp.name)
        write_tree(self.t / "base", BASE_MODULES, BASE_DATA, BASE_CHUNKS)
        write_tree(self.t / "mod", MOD_MODULES, MOD_DATA, MOD_CHUNKS)
        dol(self.t / "base.dol")
        dol(self.t / "mod.dol", text=b"\x60\x00\x00\x00\x38\x60\x00\x01\x60\x00\x00\x00\x60\x00\x00\x00")

    def tearDown(self):
        self.tmp.cleanup()

    def run_tool(self, *extra, tree="base", mod=None):
        mod = mod or "mod"
        r = subprocess.run([sys.executable, str(BUILD), "--composite-src", str(self.t / tree), "--base-dol",
                            str(self.t / "base.dol"), "--mod", "rando:%s:%s" % (self.t / mod, self.t / "mod.dol"),
                            *extra], capture_output=True, text=True)
        return r

    def test_layout_and_overlay(self):
        # Windows paths hold a colon: run the same call through the module's functions instead of the command line
        # for the parts that need none, and check the text the tool writes for the rest.
        base, mod = bmv.rel_layout(self.t / "base"), bmv.rel_layout(self.t / "mod")
        text = "\n".join(bmv.layout_lines("rando", base, mod))
        # the changed section tables are the mod's own, the unchanged module 6's data image is rebuilt (it grew)
        self.assertIn("s_mod_rel_sec_rando_5[]", text)
        self.assertIn("s_mod_rel_sec_rando_9[]", text)
        self.assertIn("s_mod_rel_sec_rando_6[]", text)
        self.assertIn("s_mod_rel_data_rando_6_4[]", text)
        self.assertIn("s_mod_rel_data_rando_9_4[]", text)
        # an image that did not change is the base's
        self.assertRegex(text, r"\{5u, 4u, 0xC0500200u, 0x00000010u, s_rel_data_5_4\}")
        self.assertRegex(text, r"\{8u, 4u, 0xC0800200u, 0x00000010u, s_rel_data_8_4\}")
        # BSS stays NULL, at its new address
        self.assertRegex(text, r"\{5u, 6u, 0xC0500344u, 0x00000020u, NULL\}")
        # the new module is in the table, last
        mods = re.findall(r"^    \{(\d+)u, 0u, \d+u, 0x004Cu,", text, re.M)
        self.assertEqual(mods, ["5", "6", "8", "9"])
        # the module with an identical section table keeps the base's array
        self.assertIn("s_mod_rel_sec_rando_8[]", text)

    def test_overlaid(self):
        extras = [(0, 0xC0800084, 0xC08001C4, "f")]
        self.assertEqual(bmv.overlaid_chunks({0xC08000F4: 0xC0800180, 0xC0800180: 0xC08001C0}, extras),
                         {0xC08000F4: 0xC0800180, 0xC0800180: 0xC08001C0})
        # an extra that stops short of the base chunk's end is refused
        with self.assertRaises(SystemExit):
            bmv.overlaid_chunks({0xC08000F4: 0xC0800180}, [(0, 0xC0800084, 0xC0800100, "f")])
        # extras that only sit beside the base chunks overlay nothing
        self.assertEqual(bmv.overlaid_chunks({0xC0500100: 0xC0500200}, [(0, 0xC0500300, 0xC0500340, "f")]), {})

    def test_tool_end_to_end(self):
        # build_mod_variants parses its --mod spec on ':': the test trees are under a Windows temp dir with a drive
        # letter, so run from the temp dir with relative paths, as scripts/windows/build.py does.
        self.before = (self.t / "base" / "rel_modules.inc").read_text()
        r = subprocess.run([sys.executable, str(BUILD), "--composite-src", "base", "--base-dol", "base.dol",
                            "--mod", "rando:mod:mod.dol", "--layout", "rando"], capture_output=True, text=True, cwd=self.t)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        inc = (self.t / "base" / "mod_variants.inc").read_text()
        self.assertIn("module layout", r.stdout)
        self.assertIn("MODULE_MOD_LAYOUT_COUNT 1u", inc)
        self.assertIn("static void bluewake_mod_overlay", inc)
        # the replaced chest chunk's base chunk starts are overlays; the other base chunk is a plain variant
        self.assertRegex(inc, r"\{0x1u, 0xC08000F4u, bluewake_mod_overlay\}")
        self.assertRegex(inc, r"\{0x1u, 0xC0800180u, bluewake_mod_overlay\}")
        self.assertRegex(inc, r"\{0x1u, 0xC0500100u, func_C0500100__mod_rando\}")
        self.assertNotRegex(inc, r"0xC0600100u, func_")  # unchanged chunk: no variant
        # the extras: section 7, the new module, the replaced chest chunk
        self.assertEqual(len(re.findall(r"\{0u, 0xC0[0-9A-F]{6}u, 0xC0[0-9A-F]{6}u, func_", inc)), 3)
        # REL data of the layout mod is not written at boot (the layout carries it)
        self.assertNotIn("0xC0600200u, 24u", inc)
        # base tables of the variant tree are untouched
        self.assertEqual((self.t / "base" / "rel_modules.inc").read_text(), self.before)

    def test_switchable_chunks_go_through_trampolines(self):
        # --switchable: every chunk start a switchable mod's variants replace gets a trampoline whose target the module
        # sets (bluewake_composite_set_mods); the starts are sorted for the module's binary search.
        r = subprocess.run([sys.executable, str(BUILD), "--composite-src", "base", "--base-dol", "base.dol",
                            "--mod", "rando:mod:mod.dol", "--layout", "rando", "--switchable", "rando"],
                           capture_output=True, text=True, cwd=self.t)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        inc = (self.t / "base" / "mod_variants.inc").read_text()
        self.assertIn("MODULE_MOD_SWITCH_MASK 0x1u", inc)
        self.assertIn("MODULE_MOD_SWITCH_COUNT 3u", inc)
        starts = re.search(r"s_mod_switch_starts\[MODULE_MOD_SWITCH_COUNT\] = \{([^}]*)\}", inc).group(1)
        values = [int(v.strip().rstrip("u"), 16) for v in starts.split(",")]
        self.assertEqual(values, sorted(values))
        self.assertEqual(values, [0xC0500100, 0xC08000F4, 0xC0800180])
        for i in range(3):
            self.assertIn("static void bluewake_mod_switch_tramp_%d(CPUState* ctx) { s_mod_switch_target[%d](ctx); }" % (i, i), inc)
        # a mod that is not switchable gets none
        r = subprocess.run([sys.executable, str(BUILD), "--composite-src", "base", "--base-dol", "base.dol",
                            "--mod", "rando:mod:mod.dol", "--layout", "rando"], capture_output=True, text=True, cwd=self.t)
        inc = (self.t / "base" / "mod_variants.inc").read_text()
        self.assertIn("MODULE_MOD_SWITCH_COUNT 0u", inc)
        self.assertNotIn("bluewake_mod_switch_tramp", inc)
        # naming a mod the build does not have is an error
        r = subprocess.run([sys.executable, str(BUILD), "--composite-src", "base", "--base-dol", "base.dol",
                            "--mod", "rando:mod:mod.dol", "--layout", "rando", "--switchable", "nosuch"],
                           capture_output=True, text=True, cwd=self.t)
        self.assertNotEqual(r.returncode, 0)

    def test_appended_code_gets_an_image(self):
        # Module 5 gains an executable section 7 (free-space code with a table): its file bytes become its data image.
        rel = bytearray(0x400)
        rel[0:4] = (5).to_bytes(4, "big")
        rel[12:16] = (8).to_bytes(4, "big")
        rel[16:20] = (0x4C).to_bytes(4, "big")
        entry = 0x4C + 7 * 8
        rel[entry:entry + 8] = (0x300 | 1).to_bytes(4, "big") + (0x40).to_bytes(4, "big")
        rel[0x300:0x340] = bytes(range(0x40))
        with tempfile.TemporaryDirectory() as td:
            (Path(td) / "zz_mod.rel").write_bytes(bytes(rel))
            base, mod = bmv.rel_layout(self.t / "base"), bmv.rel_layout(self.t / "mod")
            images = bmv.appended_code_images(base, mod, td)
        self.assertEqual(list(images), [(5, 7)])
        self.assertEqual(images[(5, 7)], (0xC0500300, 0x40, bytes(range(0x40))))

    def test_no_layout_still_refuses_changed_shape(self):
        r = subprocess.run([sys.executable, str(BUILD), "--composite-src", "base", "--base-dol", "base.dol",
                            "--mod", "plain:mod:mod.dol"], capture_output=True, text=True, cwd=self.t)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("changed shape", r.stdout + r.stderr)


class Check(unittest.TestCase):
    def layout(self, modules, data):
        with tempfile.TemporaryDirectory() as td:
            write_tree(td, modules, data, {})
            return bmv.rel_layout(td)

    def test_clean_layouts(self):
        self.assertEqual(cv.check_layout(self.layout(BASE_MODULES, BASE_DATA), {}), [])
        self.assertEqual(cv.check_layout(self.layout(MOD_MODULES, MOD_DATA), {}), [])

    def test_overlap(self):
        modules = dict(BASE_MODULES)
        modules[6] = (0x300, [(0, 0, 0), (1, 0xC0500180, 0x100), (4, 0xC0600200, 0x10)])  # runs into module 5's section 4
        problems = cv.check_layout(self.layout(modules, BASE_DATA), {})
        self.assertTrue(any("overlap" in p for p in problems), problems)

    def test_chunk_outside_sections(self):
        layout = self.layout(BASE_MODULES, BASE_DATA)
        self.assertEqual(cv.check_layout(layout, {0xC0500100: 0xC0500200}), [])
        problems = cv.check_layout(layout, {0xC0500100: 0xC0500300})
        self.assertTrue(any("no section" in p for p in problems), problems)

    def test_data_entry_off_table(self):
        layout = self.layout(BASE_MODULES, BASE_DATA)
        layout["data"][(6, 4)] = (0xC0600204, 0x10, b"\x00" * 16)
        problems = cv.check_layout(layout, {})
        self.assertTrue(any("data entry" in p for p in problems), problems)

    def test_compare(self):
        diff = cv.compare(self.layout(BASE_MODULES, BASE_DATA), self.layout(MOD_MODULES, MOD_DATA))
        self.assertEqual(diff["new_modules"], [9])
        self.assertEqual(diff["changed_modules"], [5, 6, 8])
        self.assertEqual(diff["problems"], [])


if __name__ == "__main__":
    unittest.main()
