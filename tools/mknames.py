# Makes config/GZLE01/names.txt from the linker map Nintendo left on the disc (orig/maps/framework.map,
# from tools/extract.py): every main.dol function, named - SDK functions in the libraries the
# runtime replaces by name (src/recompiler/build.cpp: hleLibraries) and the game's own, so host code
# (replacements, enhancement hooks) can take over any of them by name.
#   python tools/mknames.py [orig/maps/framework.map] [config/GZLE01/names.txt]
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else 'orig/maps/framework.map'
dst = sys.argv[2] if len(sys.argv) > 2 else 'config/GZLE01/names.txt'
# "  00297e80 000260 8029d560  4 __start__Q27JAInter9StreamLibFv 	JAudio.a JAIStreamMgr.cpp"
#   (an object of the game itself has no archive: "  ... 4 main 	m_Do_main.o")
line_re = re.compile(r'\s+[0-9a-f]{8} ([0-9a-f]{6}) ([0-9a-f]{8})\s+\d+ (\S+)\s+(\S+)(?: (\S+))?\s*$')
seen = set()
rows = []
in_text = False
for line in open(src, encoding='latin1'):
    if line.startswith('.text section layout'):
        in_text = True
        continue
    if in_text and line.endswith('section layout\n'):
        break
    m = line_re.match(line) if in_text else None
    if not m:
        continue
    size, addr, name, first, second = m.groups()
    # (any alignment: 4, or 32 for JAudio's DSP code and others; section entries are .text)
    if int(size, 16) == 0 or addr in seen or name.startswith('.'):
        continue
    seen.add(addr)
    if second:  # archive + object
        lib, tu = first[:-2] if first.endswith('.a') else first, second
    else:
        lib, tu = 'game', first
    rows.append((int(addr, 16), name, lib, tu))
rows.sort()
with open(dst, 'w', newline='\n') as f:
    f.write('# The Wind Waker (GZLE01) main.dol: address name library translation-unit\n')
    f.write('# Generated by tools/mknames.py from the disc\'s maps/framework.map. Never edit by hand.\n')
    for a, name, lib, tu in rows:
        f.write(f'{a:08X} {name} {lib} {tu}\n')
print(f'{len(rows)} functions -> {dst}')
