# Turns Boat of Daphnes' option list (mods/betterww/options.txt, GPL-3.0-or-later, by
# AgitationSkeleton: Better Wind Waker's settings and more as switches) into the table the
# runtime's game options use (src/runtime/bod/options.inc):
#   option NAME INDEX on|off TITLE...     a switch
#   site   WHERE NAME insn|imm16 VALUE     an instruction replaced while it is on
#   hook   WHERE NAME before|after ID      native code at WHERE (src/runtime/bod/gameopts.cpp)
#   write  WHERE NAME f32|u32|u16|u8 VALUE a value written while it is on
# WHERE is a main.dol address or MODULE.rel+OFFSET, an offset in the REL file: resolved here to
# the module's id, section and offset in it, from the disc's RELs (orig/rel).
#   gen_bod_options.py <options.txt> <orig/rel> <out.inc>
import struct, sys, os

src, reldir, out = sys.argv[1:4]
rels = {}

def where(w):
    if '.rel+' not in w:
        return (0, 0, int(w, 16))  # module 0: main.dol, absolute address
    name, off = w.split('.rel+')
    off = int(off, 16)
    if name not in rels:
        d = open(os.path.join(reldir, name + '.rel'), 'rb').read()
        mid, _, _, ns, so = struct.unpack('>IIIII', d[:20])
        secs = [struct.unpack('>II', d[so + 8 * i:so + 8 * i + 8]) for i in range(ns)]
        rels[name] = (mid, secs)
    mid, secs = rels[name]
    for i, (o, s) in enumerate(secs):
        o &= ~1
        if o and o <= off < o + s:
            return (mid, i, off - o)
    sys.exit(f'{w}: not in a section of {name}.rel')

options, sites, hooks, writes = [], [], [], []
for line in open(src, encoding='utf-8'):
    line = line.split('#', 1)[0].strip()
    if not line:
        continue
    f = line.split()
    if f[0] == 'option':
        options.append((f[1], int(f[2]), f[3] == 'on', ' '.join(f[4:])))
    elif f[0] == 'site':
        m, s, o = where(f[1])
        sites.append((f[2], m, s, o, f[3] == 'imm16', int(f[4], 16)))
    elif f[0] == 'hook':
        m, s, o = where(f[1])
        hooks.append((f[2], m, s, o, f[3] == 'after', int(f[4])))
    elif f[0] == 'write':
        m, s, o = where(f[1])
        t, v = f[3], f[4]
        if t == 'f32':
            bits, size = struct.unpack('>I', struct.pack('>f', float(v)))[0], 4
        else:
            bits, size = int(v, 0), {'u32': 4, 'u16': 2, 'u8': 1}[t]
        writes.append((f[2], m, s, o, size, bits))
    else:
        sys.exit(f'unknown line: {line}')

idx = {name: i for i, (name, *_ ) in enumerate(options)}
def opt(name):
    if name not in idx:
        sys.exit(f'unknown option {name}')
    return idx[name]

with open(out, 'w', encoding='utf-8', newline='\n') as o:
    o.write('// Generated by tools/gen_bod_options.py from Boat of Daphnes\' mods/betterww/options.txt\n')
    o.write('// (GPL-3.0-or-later). Do not edit: change the list and run the tool.\n')
    o.write('// {module, section, offset}: module 0 is main.dol and the offset an address.\n')
    o.write('constexpr OptionDef kOptions[] = {\n')
    for name, index, on, title in options:
        o.write(f'    {{"{name}", {index}, {str(on).lower()}, "{title}"}},\n')
    o.write('};\nconstexpr SiteDef kSites[] = {\n')
    for name, m, s, off, imm, v in sites:
        o.write(f'    {{{opt(name)}, {{{m}, {s}, 0x{off:X}}}, {str(imm).lower()}, 0x{v:08X}}},  // {name}\n')
    o.write('};\nconstexpr HookDef kHooks[] = {\n')
    for name, m, s, off, after, hid in hooks:
        o.write(f'    {{{opt(name)}, {{{m}, {s}, 0x{off:X}}}, {str(after).lower()}, {hid}}},  // {name}\n')
    o.write('};\nconstexpr WriteDef kWrites[] = {\n')
    for name, m, s, off, size, bits in writes:
        o.write(f'    {{{opt(name)}, {{{m}, {s}, 0x{off:X}}}, {size}, 0x{bits:08X}}},  // {name}\n')
    o.write('};\n')
print(f'{out}: {len(options)} options, {len(sites)} sites, {len(hooks)} hooks, {len(writes)} writes, {len(rels)} RELs')
