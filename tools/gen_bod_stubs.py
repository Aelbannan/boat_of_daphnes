# Writes src/bod/shim/bod_stubs.c: Boat of Daphnes host functions this runtime does not provide yet,
# each with the declaration its own header gives (so the signatures are its), returning nothing / 0 /
# false / NULL - what its menus see of a host without that part (online play, the randomizer's
# in-place switch, the GBA, mod archives...). Remove a name here when its part is ported.
#   gen_bod_stubs.py
import os, re

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'bod')
NAMES = '''
bluewake_dsp_request_mode bluewake_gba_set_mode
bluewake_player_model_live bluewake_player_model_swap bluewake_puppet_drawn bluewake_puppet_enable
bluewake_puppet_local_pose bluewake_puppet_remote_clear bluewake_puppet_remote_model bluewake_puppet_remote_remove
bluewake_puppet_remote_show bluewake_puppet_remote_update bluewake_puppet_self_test bluewake_puppet_set_sounds
bluewake_rando_inplace_can_leave bluewake_rando_inplace_poll bluewake_rando_inplace_ready bluewake_rando_inplace_request
bluewake_rando_option bluewake_rando_session_runs_it bluewake_rando_set_pack bluewake_rando_ui_bgm bluewake_rando_ui_scene
bluewake_rando_ui_sfx bluewake_rando_ui_subbgm bluewake_team_sync_enable bluewake_team_sync_give
bluewake_team_sync_snapshot bluewake_team_sync_take bluewake_ui_pad_inject bluewake_ui_pad_set_focus
bluewake_ui_pad_set_gate bluewake_ui_pad_take_pressed
gba_link_audio_rate gba_link_copy_frame gba_link_read_audio gba_link_reset gba_link_running gba_link_stats

'''.split()

headers = []
for d, _, files in os.walk(ROOT):
    for f in files:
        if f.endswith(('.h', '.cpp')):
            headers.append(os.path.join(d, f))
headers.sort(key=lambda h: not h.endswith('.h'))  # a header's declaration first

found, includes = {}, set()
for h in headers:
    text = open(h, encoding='utf-8', errors='replace').read()
    flat = re.sub(r'//[^\n]*|/\*.*?\*/', ' ', text, flags=re.S)
    for name in NAMES:
        if name in found:
            continue
        m = re.search(r'(^|[;}\n])\s*((?:const\s+)?[A-Za-z_][\w\s\*]*?[\s\*])' + name + r'\s*\(([^;{]*?)\)\s*;', flat)
        if m:
            found[name] = (m.group(2).strip(), m.group(3).strip())
            if h.endswith('.h'):  # (declared in a source file: repeated below instead)
                rel = os.path.relpath(h, ROOT).replace('\\', '/')
                for prefix in ('runtime/host/src/', 'include/'):
                    if rel.startswith(prefix):
                        rel = rel[len(prefix):]
                includes.add(rel)

missing = [n for n in NAMES if n not in found]
if missing:
    raise SystemExit('no declaration found for: ' + ' '.join(missing))

def body(ret):
    r = ret.replace('static', '').replace('inline', '').strip()
    if r == 'void':
        return ''
    if r.endswith('*'):
        return ' return NULL;'
    if r == 'bool':
        return ' return false;'
    if re.fullmatch(r'(unsigned\s+)?(int|long|long long|short|char)|u?int\d+_t|u\d+|s\d+|size_t|float|double|unsigned', r):
        return ' return 0;'
    return ' ' + r + ' zero; memset(&zero, 0, sizeof zero); return zero;'

out = os.path.join(ROOT, 'shim', 'bod_stubs.c')
with open(out, 'w', encoding='utf-8', newline='\n') as o:
    o.write('/* Generated by tools/gen_bod_stubs.py: Boat of Daphnes host functions not ported yet, as a host\n'
            ' * without them answers (declarations from its own headers). Do not edit; regenerate. */\n')
    o.write('#include <stdbool.h>\n#include <stddef.h>\n#include <string.h>\n')
    for inc in sorted(includes):
        o.write(f'#include "{inc}"\n')
    for name in NAMES:
        ret, args = found[name]
        params = []
        for i, a in enumerate([x.strip() for x in args.split(',')] if args and args != 'void' else []):
            params.append(a)
        def pname(p):  # a parameter's name (a function pointer's inside its parentheses)
            m = re.search(r'\(\s*\*\s*(\w+)\s*\)', p)
            return m.group(1) if m else p.split()[-1].lstrip('*').split('[')[0]
        o.write(f'{ret} {name}({", ".join(params) if params else "void"}) {{' + ''.join(
            f' (void){pname(p)};' for p in params if p != '...') + body(ret) + ' }\n')
print(out, len(NAMES), 'stubs from', len(includes), 'headers')
