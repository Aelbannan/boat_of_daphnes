#!/usr/bin/env python3
"""Make windows/src/ww_names.inc: the game's item and process (actor) names, for the Dev Tools windows.

    python scripts/windows/gen_ww_names.py [path to tww-main]

The names are the zeldaret/tww decomp's (CC0): dItemNo_*_e in include/d/d_item_data.h and fpcNm_*_e in
include/f_pc/f_pc_name.h. The output is checked in, so a build does not need the decomp.
"""
import re
import sys
from pathlib import Path
import sys as _bod_sys
from pathlib import Path as _BodPath
_bod_sys.path.insert(0, str(_BodPath(__file__).resolve().parents[1]))
try:
    from bod_paths import local_path, scratch  # noqa: E402  (scripts/bod_paths.py)
except ImportError:  # a release's copy of this script, without the repository's scripts/ beside it
    import os as _bod_os

    def local_path(name, fallback=""):
        return _bod_os.environ.get(name) or fallback

    def scratch():
        return _BodPath(local_path("BOD_SCRATCH", "scratch"))

tww = Path(sys.argv[1] if len(sys.argv) > 1 else local_path("BOD_TWW_DECOMP"))
out = Path(__file__).resolve().parents[2] / "windows/src/ww_names.inc"


def table(path, prefix):
    names = {}
    for m in re.finditer(r"/\* 0x([0-9A-Fa-f]+) \*/\s+(" + prefix + r"\w+?)_e\b", path.read_text()):
        names[int(m.group(1), 16)] = m.group(2)[len(prefix):]
    return names


items = table(tww / "include/d/d_item_data.h", "dItemNo_")
procs = table(tww / "include/f_pc/f_pc_name.h", "fpcNm_")
lines = ["// Generated by scripts/windows/gen_ww_names.py from the zeldaret/tww decomp (CC0). Do not edit.",
         "static const struct { int id; const char* name; } kItemNames[] = {"]
lines += [f'    {{0x{i:02X}, "{n}"}},' for i, n in sorted(items.items())]
lines += ["};", "static const struct { int id; const char* name; } kProcNames[] = {"]
lines += [f'    {{0x{i:04X}, "{n}"}},' for i, n in sorted(procs.items())]
lines += ["};", ""]
out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"{len(items)} items, {len(procs)} processes -> {out}")
